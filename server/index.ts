import {resolve} from 'node:path';
import {configureRuntime} from './runtime.ts';
import {openDatabase} from './db.ts';
import {createApp} from './app.ts';
import {createServer} from 'node:http';
configureRuntime();
const db=openDatabase(resolve(process.env.FOCUS_DB||'.data/focus-hub.sqlite'));
const port=Number(process.env.PORT||3000);
const server=createServer();
const development=process.env.FOCUS_DEV==='true'?await (await import('./development.ts')).developmentFrontend(server):null;
server.on('request',createApp(db,development?{frontend:development.frontend,developmentSocketOrigin:development.socketOrigin}:{}));
server.listen(port,'127.0.0.1',()=>{console.log(`Focus Hub: servidor privado en puerto ${port}${development?' · Vite con recarga automática':''}.`);if(!db.prepare('SELECT id FROM users LIMIT 1').get())console.log('Crea el propietario con npm run owner antes de iniciar sesión.');});
for(const signal of ['SIGINT','SIGTERM'] as const)process.on(signal,()=>{void (async()=>{await development?.close();server.close(()=>{db.close();process.exit(0);});})();});
